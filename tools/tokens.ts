emit("fixtures/tokens/brand.contract.json", JSON.stringify(contract, null, 2));

// ---- packages/tokens/theme.css (shadcn set only) -------------------------------------------
const block = (sel: string, set: Record<string, { hsl: string }>, extra: string[] = []) =>
  `${sel} {\n${[...extra, ...Object.entries(set).map(([k, v]) => `  --${k}: ${v.hsl};`)].join("\n")}\n}`;
const themeKeys = Object.keys(light);
const theme = `/* Generated by tools/tokens.ts from fixtures/tokens/mapping.json. Do not edit. */
/* shadcn token set (HSL). A skin overrides these variables only; markup never changes. */
${block(":root", light, [`  --radius: ${radiusPx / 16}rem;`, `  --font-sans: "${mapping.font.sans}", ui-sans-serif, system-ui, sans-serif;`])}

${block(".dark,\n[data-theme=\"dark\"]", dark)}

@theme inline {
${themeKeys.map((k) => `  --color-${k}: var(--${k});`).join("\n")}
  --radius-sm: calc(var(--radius) * 0.25);
  --radius-md: calc(var(--radius) * 0.5);
  --radius-lg: var(--radius);
  --radius-xl: calc(var(--radius) * 1.5);
  --font-sans: var(--font-sans);
}
`;
emit("packages/tokens/theme.css", theme);

// ---- brand extras (apps only) -------------------------------------------------------------
const brandCss = (where: string) => `/* Generated by tools/tokens.ts. Brand tokens without a shadcn role: ${where} only, never packages/. */
${block(":root", brandLight)}

${block(".dark,\n[data-theme=\"dark\"]", brandDark)}

@theme inline {
${Object.keys(brandLight).map((k) => `  --color-${k}: var(--${k});`).join("\n")}
  --text-display: 5.3125rem;
  --text-display--line-height: 1;
  --container-page: 77.5rem;
}
`;
emit("apps/site/styles/brand.css", brandCss("apps/site"));
emit("apps/design/src/lib/styles/brand.css", brandCss("apps/design"));

let drift = 0;
for (const [p, s] of outputs) {
  const full = join(ROOT, p);
  const old = existsSync(full) ? readFileSync(full, "utf8") : null;
  if (old === s) continue;
  if (CHECK) { console.error(`drift: ${p} differs (run: bun run tokens)`); drift++; continue; }
  mkdirSync(dirname(full), { recursive: true });
  writeFileSync(full, s);
  console.log(`wrote ${p}`);
}
if (CHECK && drift) process.exit(1);
if (CHECK) console.log(`tokens: ${outputs.length} files up to date`);
