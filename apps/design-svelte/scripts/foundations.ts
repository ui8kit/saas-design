/**
 * Writes src/lib/styles/foundations.generated.css: one semantic ds-* class per foundation sample
 * (color swatch, type step, spacing step, radius, shadow). Utilities only inside @apply.
 *   bun scripts/foundations.ts [--check]
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, resolve } from "node:path";

const APP = resolve(import.meta.dir, "..");
const CHECK = process.argv.includes("--check");

import { colorNames, typeSteps, spaceSteps, radii, shadows } from "../src/lib/foundations.ts";

const out: string[] = ["/* Generated by apps/design-svelte/scripts/foundations.ts. Do not edit. */", "@layer components {"];
for (const c of colorNames) out.push(`  .ds-swatch-${c} { @apply bg-${c}; }`);
for (const t of typeSteps) out.push(`  .ds-type-${t} { @apply text-${t}; }`);
for (const s of spaceSteps) out.push(`  .ds-space-${s} { @apply size-${s}; }`);
for (const r of radii) out.push(`  .ds-radius-${r} { @apply rounded-${r}; }`);
for (const s of shadows) out.push(`  .ds-shadow-${s} { @apply ${s === "base" ? "shadow" : `shadow-${s}`}; }`);
out.push("}");
const body = out.join("\n") + "\n";
const p = join(APP, "src/lib/styles/foundations.generated.css");
if (CHECK) {
  if (!existsSync(p) || readFileSync(p, "utf8") !== body) { console.error("drift: src/lib/styles/foundations.generated.css"); process.exit(1); }
} else writeFileSync(p, body);
console.log(`design foundations: ${colorNames.length} colors, ${typeSteps.length} type, ${spaceSteps.length} space, ${radii.length} radii, ${shadows.length} shadows ${CHECK ? "checked" : "written"}`);
