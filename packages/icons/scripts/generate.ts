/**
 * Icon registry for both runtimes: Lucide (lucide-static icon-nodes.json) + project brand marks
 * (fixtures/media/svg). Emits identical SVG strings for Go (templ/icons.go) and TS (src/icons.generated.ts).
 *   bun scripts/generate.ts [--check]
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, resolve } from "node:path";
import { execFileSync } from "node:child_process";

const ROOT = resolve(import.meta.dir, "../../..");
const CHECK = process.argv.includes("--check");
export const LUCIDE = [
  "activity", "arrow-right", "bell", "calendar", "chart-line", "check", "chevron-down", "chevron-right", "circle-check", "cloud",
  "flame", "heart-pulse", "inbox", "instagram", "layout-template", "linkedin", "list-plus", "lock", "mail", "menu", "message-square",
  "notebook-pen", "play", "plus", "search", "settings", "shield-check", "star", "target", "timer", "trending-up", "x", "zap", "apple", "smartphone",
];
const BRAND = ["brand-mark"];

const nodes = JSON.parse(readFileSync(join(ROOT, "node_modules/lucide-static/icon-nodes.json"), "utf8")) as Record<string, [string, Record<string, string>][]>;
const esc = (s: string) => s.replace(/&/g, "&amp;").replace(/"/g, "&quot;");
const icons: Record<string, { viewBox: string; inner: string; stroke: boolean }> = {};
for (const name of LUCIDE) {
  const n = nodes[name];
  if (!n) throw new Error(`lucide icon not found: ${name}`);
  icons[name] = { viewBox: "0 0 24 24", stroke: true, inner: n.map(([tag, a]) => `<${tag} ${Object.entries(a).map(([k, v]) => `${k}="${esc(String(v))}"`).join(" ")}/>`).join("") };
}
for (const name of BRAND) {
  const svg = readFileSync(join(ROOT, `fixtures/media/svg/${name}.svg`), "utf8");
  const viewBox = /viewBox="([^"]+)"/.exec(svg)![1]!;
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
  icons[name] = { viewBox, inner, stroke: false };
}
const names = Object.keys(icons).sort();

const go = `// Code generated by packages/icons/scripts/generate.ts. DO NOT EDIT.
// Lucide icons (ISC, lucide-static v0.460.0) + Habitus brand marks.

package icons

import "github.com/a-h/templ"

type icon struct{ viewBox, inner string; stroke bool }

var registry = map[string]icon{
${names.map((n) => `\t${JSON.stringify(n)}: {${JSON.stringify(icons[n]!.viewBox)}, ${JSON.stringify(icons[n]!.inner)}, ${icons[n]!.stroke}},`).join("\n")}
}

// SVG returns a decorative inline SVG. class is a semantic ui-* class; unknown names render nothing.
func SVG(name, class string) string {
\ti, ok := registry[name]
\tif !ok {
\t\treturn ""
\t}
\tpaint := \`fill="currentColor"\`
\tif i.stroke {
\t\tpaint = \`fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"\`
\t}
\treturn \`<svg xmlns="http://www.w3.org/2000/svg" viewBox="\` + i.viewBox + \`" \` + paint + \` class="\` + class + \`" aria-hidden="true" focusable="false">\` + i.inner + \`</svg>\`
}

// Icon is the templ component of SVG: blocks render \`@icons.Icon(name, class)\`, so the one raw-HTML write of an icon
// lives here (the registry is static, generated from lucide-static and fixtures/media/svg), never in composition code.
func Icon(name, class string) templ.Component { return templ.Raw(SVG(name, class)) }

// Names lists the registered icons.
func Names() []string { return []string{${names.map((n) => JSON.stringify(n)).join(", ")}} }
`;
const ts = `// Code generated by packages/icons/scripts/generate.ts. DO NOT EDIT.
// Lucide icons (ISC, lucide-static v0.460.0) + Habitus brand marks.

export type Icon = { viewBox: string; inner: string; stroke: boolean };
const registry: Record<string, Icon> = ${JSON.stringify(icons, null, 2)};

/** Decorative inline SVG — byte-identical to Go icons.SVG. */
export function svg(name: string, cls: string): string {
  const i = registry[name];
  if (!i) return "";
  const paint = i.stroke ? 'fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"' : 'fill="currentColor"';
  return \`<svg xmlns="http://www.w3.org/2000/svg" viewBox="\${i.viewBox}" \${paint} class="\${cls}" aria-hidden="true" focusable="false">\${i.inner}</svg>\`;
}

/** Registry entry (React renders the <svg> element itself and sets inner as innerHTML: same DOM as svg()). */
export function icon(name: string): Icon | undefined { return registry[name]; }

export const iconNames: string[] = ${JSON.stringify(names)};
`;
const out: Record<string, string> = { "templ/icons.go": execFileSync("gofmt", [], { input: go, encoding: "utf8" }), "src/icons.generated.ts": ts };
let drift = 0;
for (const [rel, body] of Object.entries(out)) {
  const p = join(import.meta.dir, "..", rel);
  if (CHECK) { if (!existsSync(p) || readFileSync(p, "utf8") !== body) { console.error(`drift: packages/icons/${rel}`); drift++; } }
  else writeFileSync(p, body);
}
console.log(`icons: ${names.length} icons ${CHECK ? "checked" : "written"}`);
if (drift) process.exit(1);
