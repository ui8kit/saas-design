/**
 * @saas-design/ui generator.
 *
 * 1. Load the brick registry of @ui8kit/codegen (pinned git dependency, see package.json).
 * 2. Replace upstream recipes with the brand-neutral, token-only recipes in ./recipes (same keys).
 * 3. Rewrite EVERY class string a brick can emit (recipes, staticBase, extra expressions, state, inner
 *    class specs) into a semantic `ui-*` class. The original utilities go into
 *    packages/adapter/src/primitives.generated.css as `.ui-x { @apply ...; }`.
 *    => generated markup carries only ui-* classes; utilities live only inside @apply.
 * 4. Emit Go templ (./templ) and Svelte 5 (./svelte) with @ui8kit/codegen's emitters.
 *
 *   bun scripts/generate.ts           write
 *   bun scripts/generate.ts --check   fail on drift (validates the registry first)
 */
import { readFileSync, existsSync } from "node:fs";
import { join, resolve } from "node:path";
import { bricks as upstream } from "@ui8kit/codegen/bricks/index";
import { validateRegistry } from "@ui8kit/codegen/src/domain/validate";

const PKG = resolve(import.meta.dir, "..");
export const GO_MODULE = "github.com/ui8kit/saas-design/packages/ui/templ";

const kebab = (s: string) => s.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
export const css = new Map<string, string>(); // semantic class -> utilities
const origin = new Map<string, string>(); // semantic class -> where
function define(name: string, utilities: string, where: string): string {
  // Marker classes (group, peer) cannot be @applied in Tailwind v4 and carry no styling; no brick uses group-*/peer-* variants.
  // Half steps from upstream bricks are snapped to the 8+4 grid (.project/backlog/codegen-half-steps.md).
  const SNAP: Record<string, string> = { "gap-1.5": "gap-2" };
  const u = utilities.trim().split(/\s+/).filter((t) => !/^(group|peer)(\/.*)?$/.test(t)).map((t) => SNAP[t] ?? t).join(" ");
  if (!u) return "";
  const prev = css.get(name);
  if (prev !== undefined && prev !== u) throw new Error(`semantic class ${name} defined twice with different utilities (${origin.get(name)} / ${where})`);
  css.set(name, u);
  origin.set(name, where);
  return name;
}

// ---- recipes ----------------------------------------------------------------------------------
function semanticRecipe(dir: string, file: string, recipe: any): any {
  const over = join(PKG, "recipes", file);
  const src = existsSync(over) ? JSON.parse(readFileSync(over, "utf8")) : recipe;
  const upKeys: string[] = recipe.keys ?? [];
  const srcKeys: string[] = src.keys ?? [];
  if ([...upKeys].sort().join() !== [...srcKeys].sort().join()) throw new Error(`${file}: keys ${srcKeys} != upstream ${upKeys}`);
  for (const k of upKeys) for (const v of Object.keys(recipe.byKey[k] ?? {}))
    if (!(v in (src.byKey[k] ?? {}))) throw new Error(`${file}: missing ${k}.${v} (upstream has it)`);
  const stem = file.replace(".variants.json", "");
  const name = `ui-${stem}`;
  const out: any = { $comment: `Generated by packages/ui/scripts/generate.ts from ${existsSync(over) ? `packages/ui/recipes/${file}` : `@ui8kit/codegen bricks/${dir}/${file}`}. Classes are defined in @saas-design/adapter.`, id: recipe.id, base: define(name, src.base, `${file}:base`), keys: upKeys, defaults: src.defaults ?? recipe.defaults, byKey: {} };
  for (const k of upKeys) {
    out.byKey[k] = {};
    for (const [v, utils] of Object.entries(src.byKey[k] as Record<string, string>)) {
      out.byKey[k][v] = define(k === "variant" ? `${name}-${v}` : `${name}-${k}-${v}`, utils, `${file}:${k}.${v}`);
    }
  }
  if (recipe.compound?.length || src.compound?.length) throw new Error(`${file}: compound variants are not supported by this generator yet`);
  return out;
}

// ---- non-recipe class positions ----------------------------------------------------------------
function rewriteString(s: string, ctx: string): string {
  const t = s.trim();
  if (!t) return s;
  if (t.split(/\s+/).every((x) => x.startsWith("ui-"))) return t;
  const m = /^grid-cols-(\d+)$/.exec(t) ?? /^grid-cols-1 md:grid-cols-2(?: xl:grid-cols-(\d+))?$/.exec(t);
  if (/^grid-cols-\d+$/.test(t)) return define(`ui-cols-${t.slice(10)}`, t, ctx);
  if (m && t.includes("md:")) return define(`ui-cols-1-${m[1] ?? 2}`, t, ctx);
  const span = /^(col-span|col-start|col-end|order)-(\d+)$/.exec(t);
  if (span) return define(`ui-${span[1]!.replace("col-", "")}-${span[2]}`, t, ctx);
  if (t === "pointer-events-none opacity-50") return define("ui-disabled", t, ctx);
  // context-named class: a second, different utility set in the same context gets a numeric suffix
  for (let i = 1; ; i++) {
    const name = i === 1 ? `ui-${ctx}` : `ui-${ctx}-${i}`;
    const prev = css.get(name);
    if (prev === undefined || prev === t.replace(/\s+/g, " ")) return define(name, t, ctx);
  }
}
function rewriteExpr(e: any, ctx: string): any {
  if (!e || typeof e !== "object") return e;
  switch (e.kind) {
    case "lit": return typeof e.value === "string" ? { ...e, value: rewriteString(e.value, ctx) } : e;
    case "mapOr": case "intMapOr":
      return { ...e, mapping: Object.fromEntries(Object.entries(e.mapping).map(([k, v]) => [k, rewriteString(String(v), ctx)])), fallback: typeof e.fallback === "string" ? rewriteString(e.fallback, ctx) : e.fallback };
    case "cond": return { ...e, then: rewriteExpr(e.then, ctx), else: rewriteExpr(e.else, ctx) };
    case "concat": return { ...e, parts: e.parts.map((p: any) => rewriteExpr(p, ctx)) };
    case "defaultIfEmpty": throw new Error(`${ctx}: defaultIfEmpty in a class position is not supported`);
    default: return e; // prop, item, derived ...: caller-provided values, never rewritten
  }
}
function rewriteSpec(c: any, ctx: string): any {
  if (!c) return c;
  const out = { ...c };
  if (c.staticBase) out.staticBase = rewriteString(c.staticBase, ctx);
  if (c.extra) out.extra = c.extra.map((x: any) => rewriteExpr(x, ctx));
  if (c.state) out.state = c.state.map((s: any) => ({ ...s, classes: rewriteString(s.classes, `${ctx}-state`) }));
  return out;
}
function rewriteNode(n: any, ctx: string, i = { n: 0 }): any {
  if (!n || typeof n !== "object") return n;
  if (Array.isArray(n)) return n.map((x) => rewriteNode(x, ctx, i));
  const out: any = { ...n };
  if (n.attrs) out.attrs = n.attrs.map((a: any) => {
    if (a.kind === "class" && a.spec) return { ...a, spec: rewriteSpec(a.spec, `${ctx}-${++i.n}`) };
    if (a.kind === "static" && a.name === "class") return { ...a, value: rewriteString(String(a.value), `${ctx}-${++i.n}`) };
    return a;
  });
  for (const k of ["children", "then", "else", "body"]) if (n[k]) out[k] = rewriteNode(n[k], ctx, i);
  return out;
}

export const bricks = upstream.map((b: any) => {
  const recipes = Object.fromEntries(Object.entries(b.recipes).map(([id, r]) => [id, semanticRecipe(b.dir, b.recipeFiles[id], r)]));
  const parts = b.parts.map((p: any) => {
    const ctx = kebab(p.name);
    return { ...p, classes: rewriteSpec(p.classes, ctx), render: rewriteNode(p.render, `${ctx}-part`) };
  });
  return { ...b, recipes, parts };
});
validateRegistry(bricks as any);

