/**
 * Writes the generated runtimes. The brick transform lives in ./registry.ts.
 *   bun scripts/generate.ts           write
 *   bun scripts/generate.ts --check   fail on drift
 */
import { existsSync, mkdirSync, writeFileSync, readdirSync, rmSync, readFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { generateFiles } from "@ui8kit/codegen/src/application/generate";
import { bricks, css, GO_MODULE } from "./registry";
import { applyRules } from "../../../tools/css-apply";

const ROOT = resolve(import.meta.dir, "../../..");
const CHECK = process.argv.includes("--check");

// ---- emit -----------------------------------------------------------------------------------------
const files = new Map<string, string>();
for (const [rt, dir] of [["templ", "templ"], ["svelte", "svelte"]] as const) {
  for (const f of await generateFiles(bricks as any, { goModule: GO_MODULE, runtimes: [rt] })) files.set(`packages/ui/${dir}/${f.path}`, f.contents);
}
const adapterCss = `/* Generated by packages/ui/scripts/generate.ts. Do not edit: change packages/ui/recipes/*.variants.json. */
/* Semantic classes emitted by the generated primitives (templ + svelte). Utilities only inside @apply. */
@layer components {
${[...css.entries()].sort(([a], [b]) => a.localeCompare(b)).flatMap(([k, v]) => applyRules(`.${k}`, v)).join("\n")}
}
`;
files.set("packages/adapter/src/primitives.generated.css", adapterCss);
files.set("packages/ui/classes.json", JSON.stringify(Object.fromEntries([...css.entries()].sort()), null, 2) + "\n");

const list = (d: string): string[] => !existsSync(join(ROOT, d)) ? [] : readdirSync(join(ROOT, d), { withFileTypes: true }).flatMap((x) => x.isDirectory() ? list(`${d}/${x.name}`) : [`${d}/${x.name}`]);
// generated trees are owned by this script; templ's *_templ.go and go.sum are produced by `templ generate`/`go mod tidy`
const owned = [...list("packages/ui/templ"), ...list("packages/ui/svelte")].filter((p) => !p.endsWith("_templ.go") && !p.endsWith("go.sum"));
let drift = 0;
for (const p of owned) if (!files.has(p)) { if (CHECK) { console.error(`drift: stale ${p}`); drift++; } else rmSync(join(ROOT, p)); }
for (const [p, s] of files) {
  const full = join(ROOT, p);
  if (existsSync(full) && readFileSync(full, "utf8") === s) continue;
  if (CHECK) { console.error(`drift: ${p} (run: bun run --cwd packages/ui generate)`); drift++; continue; }
  mkdirSync(dirname(full), { recursive: true });
  writeFileSync(full, s);
}
const partCount = bricks.reduce((n: number, b: any) => n + b.parts.length, 0);
console.log(`codegen: ${bricks.length} bricks, ${partCount} parts validated; ${files.size} files ${CHECK ? "checked" : "in sync"}; ${css.size} semantic classes`);
if (drift) process.exit(1);
