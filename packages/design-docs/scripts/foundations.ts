/**
 * Writes foundations.generated.css into each design app: one semantic ds-* class per foundation sample
 * (color swatch, type step, spacing step, radius, shadow). Utilities only inside @apply. The output uses
 * the app-level brand colors, so it lives in the apps, never in packages/
 *   bun scripts/foundations.ts [--check]
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, resolve } from "node:path";

const ROOT = resolve(import.meta.dir, "../../..");
const OUTPUTS = ["apps/design-svelte/src/lib/styles/foundations.generated.css", "apps/design-react/src/styles/foundations.generated.css"];
const CHECK = process.argv.includes("--check");

import { colorNames, typeSteps, spaceSteps, radii, shadows } from "../src/foundations.ts";

const out: string[] = ["/* Generated by packages/design-docs/scripts/foundations.ts. Do not edit. */", "@layer components {"];
for (const c of colorNames) out.push(`  .ds-swatch-${c} { @apply bg-${c}; }`);
for (const t of typeSteps) out.push(`  .ds-type-${t} { @apply text-${t}; }`);
for (const s of spaceSteps) out.push(`  .ds-space-${s} { @apply size-${s}; }`);
for (const r of radii) out.push(`  .ds-radius-${r} { @apply rounded-${r}; }`);
for (const s of shadows) out.push(`  .ds-shadow-${s} { @apply ${s === "base" ? "shadow" : `shadow-${s}`}; }`);
out.push("}");
const body = out.join("\n") + "\n";
for (const rel of OUTPUTS) {
  const p = join(ROOT, rel);
  if (CHECK) {
    if (!existsSync(p) || readFileSync(p, "utf8") !== body) { console.error(`drift: ${rel}`); process.exit(1); }
  } else writeFileSync(p, body);
}
console.log(`design foundations: ${colorNames.length} colors, ${typeSteps.length} type, ${spaceSteps.length} space, ${radii.length} radii, ${shadows.length} shadows ${CHECK ? "checked" : "written"}`);
